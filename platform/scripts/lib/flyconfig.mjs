import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');

/** Validate the settings that end up in a Fly config. Returns a list of problems. */
export function configProblems({ app, url, region }) {
  const p = [];
  if (!/^[a-z0-9][a-z0-9-]{0,62}$/.test(app || '')) p.push('The Fly app name must be lower-case letters, digits and dashes.');
  if (!/^https:\/\/[^\s"]+$/.test(url || '')) p.push('The public URL must start with https://');
  if (region && !/^[a-z]{3}$/.test(region)) p.push('The region must be a three-letter Fly region code, for example ams.');
  return p;
}

/** Fly config text for one brand, based on fly.toml. */
export function flyConfigText({ brandId, app, url, region, template = resolve(ROOT, 'fly.toml') }) {
  let toml = readFileSync(template, 'utf8');
  const swap = (re, to, what) => {
    if (!re.test(toml)) throw new Error(`fly.toml has no ${what} line to replace.`);
    toml = toml.replace(re, to);
  };
  swap(/^app = .*$/m, `app = "${app}"`, 'app');
  swap(/^(\s*)PUBLIC_URL = .*$/m, `$1PUBLIC_URL = "${url.replace(/\/$/, '')}"`, 'PUBLIC_URL');
  swap(/^(\s*)BRAND = .*$/m, `$1BRAND = "${brandId}"`, 'BRAND');
  if (region) swap(/^primary_region = .*$/m, `primary_region = "${region}"`, 'primary_region');
  return `# Generated by "npm run fly" for the ${brandId} brand. Re-run it after changing fly.toml.\n${toml}`;
}

export function writeFlyConfig({ outDir = ROOT, ...opts }) {
  const out = resolve(outDir, `fly.${opts.brandId}.toml`);
  writeFileSync(out, flyConfigText(opts));
  return out;
}
