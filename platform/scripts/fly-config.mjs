// Writes the Fly config for one brand's deployment, based on fly.toml:
//   npm run fly:config -- <brand> <fly-app-name> <public-url> [region]
//   npm run fly:config -- pulse moc-pulse https://pulse.example.com ams
// then deploy it with:  fly deploy -c fly.<brand>.toml --ha=false
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { listBrands, loadBrand } from '../server/brand.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const [brandId, app, publicUrl, region] = process.argv.slice(2);

const fail = (m) => { console.error(m); process.exit(1); };
if (!brandId || !app || !publicUrl) fail(`Usage: npm run fly:config -- <brand> <fly-app-name> <public-url> [region]\nBrands: ${listBrands().join(', ')}`);
try { loadBrand(brandId); } catch (e) { fail(e.message); }
if (!/^[a-z0-9][a-z0-9-]{0,62}$/.test(app)) fail('The Fly app name must be lower-case letters, digits and dashes.');
if (!/^https:\/\/[^\s"]+$/.test(publicUrl)) fail('The public URL must start with https://');
if (region && !/^[a-z]{3}$/.test(region)) fail('The region must be a three-letter Fly region code, for example ams.');

let toml = readFileSync(resolve(root, 'fly.toml'), 'utf8');
const swap = (re, to, what) => { if (!re.test(toml)) fail(`fly.toml has no ${what} line to replace.`); toml = toml.replace(re, to); };
swap(/^app = .*$/m, `app = "${app}"`, 'app');
swap(/^(\s*)PUBLIC_URL = .*$/m, `$1PUBLIC_URL = "${publicUrl.replace(/\/$/, '')}"`, 'PUBLIC_URL');
swap(/^(\s*)BRAND = .*$/m, `$1BRAND = "${brandId}"`, 'BRAND');
if (region) swap(/^primary_region = .*$/m, `primary_region = "${region}"`, 'primary_region');
toml = `# Generated by "npm run fly:config" for the ${brandId} brand. Re-run it after changing fly.toml.\n${toml}`;

const out = resolve(root, `fly.${brandId}.toml`);
if (existsSync(out)) console.log(`Overwriting ${out}`);
writeFileSync(out, toml);
console.log(`Wrote fly.${brandId}.toml  (app ${app}, ${publicUrl}${region ? `, region ${region}` : ''})`);
console.log(`\nNext, for this app (once):\n  fly apps create ${app}\n  fly volumes create northbound_data --app ${app} --region ${region || '<region>'} --size 1\n  fly storage create --app ${app}\n  fly secrets set --app ${app} ...   (see the README: each app needs its own SESSION_SECRET)\n  fly deploy -c fly.${brandId}.toml --ha=false`);
